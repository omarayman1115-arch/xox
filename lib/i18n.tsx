export type TranslationKey = keyof typeof translations.ar;

/* ---------- سياق اللغة ---------- */
interface LangContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  dir: "rtl" | "ltr";
  t: (key: TranslationKey) => string;
}

const LangContext = createContext<LangContextType>({
  lang: "ar",
  setLang: () => {},
  dir: "rtl",
  t: (k) => k,
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    const saved = typeof window !== "undefined" ? (localStorage.getItem("xox-lang") as Lang | null) : null;
    if (saved === "ar" || saved === "en") setLangState(saved);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("xox-lang", l);
  };

  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const t = (key: TranslationKey) => translations[lang][key] ?? translations.ar[key];

  return (
    <LangContext.Provider value={{ lang, setLang, dir, t }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}

